"""Rebuild lib/data/macro/gas.ts from the Petrobangla archive.

The Macro Trends chart "Gas Supply Transition: Domestic vs. Imported LNG" read
five hand-typed year rows. Measured against this archive's own timeline on
2026-09-16 they were wrong by a wide margin — imported LNG overstated by 245
MMCFD in 2022, 245 in 2024 and 161 in 2026, domestic understated by 174 and 133
in 2022 and 2024 — and the card claimed the series was "Tracked since 2000"
while carrying rows from 2018. The archive starts 2020-01-12, so 2018 is not
re-derived here under a different number: a row with no source in the data is
dropped, not guessed.

Method, and it travels with the figures: each year is the MEAN of the daily
MMCFD Petrobangla stated, over the days it filed — a rate averaged across the
year, never a total. Days the parser could not read, days under quarantine and
days missing either figure are excluded and counted, so a short year says how
short it is. `partial` marks a year still running (or one whose archive begins
mid-January), because a partial year drawn beside full ones reads as a fall.

Written only when a figure moves: an unchanged rebuild must not make the Pi
commit, push and republish a file whose numbers nobody changed.
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TIMELINE = ROOT / "public" / "data" / "petrobangla" / "timeline-summary.json"
TARGET = ROOT / "lib" / "data" / "macro" / "gas.ts"


def build() -> tuple[list[dict], dict]:
    days = json.loads(TIMELINE.read_text(encoding="utf-8"))["days"]
    usable: dict[str, list[tuple[float, float]]] = defaultdict(list)
    skipped: dict[str, int] = defaultdict(int)
    for day in days:
        year = str(day.get("date", ""))[:4]
        if not year:
            continue
        domestic, lng = day.get("domestic_gas"), day.get("lng_gas")
        if day.get("parse_status") != "ok" or day.get("quarantined") or domestic is None or lng is None:
            skipped[year] += 1
            continue
        usable[year].append((float(domestic), float(lng)))

    first_day = days[0]["date"] if days else ""
    last_day = days[-1]["date"] if days else ""
    rows: list[dict] = []
    for year in sorted(usable):
        vals = usable[year]
        domestic = round(sum(v[0] for v in vals) / len(vals))
        lng = round(sum(v[1] for v in vals) / len(vals))
        # A year is partial when the archive opens or ends inside it.
        partial = year == first_day[:4] and first_day[5:] != "01-01"
        partial = partial or (year == last_day[:4] and last_day[5:] != "12-31")
        rows.append({"year": year, "domestic": domestic, "lng": lng, "days": len(vals), "partial": partial})
    return rows, {"first": first_day, "last": last_day, "skipped": dict(skipped)}


def render(rows: list[dict], span: dict) -> str:
    body = "\n".join(
        "  { year: '%s', domestic: %d, lng: %d, days: %d, partial: %s },"
        % (r["year"], r["domestic"], r["lng"], r["days"], "true" if r["partial"] else "false")
        for r in rows
    )
    return f"""// Auto-generated by scripts/build_gas_mix_yearly.py — do not hand-edit.
// Canonical source: public/data/petrobangla/timeline-summary.json, rebuilt by
// every poll from the daily reports under public/data/petrobangla/daily.
//
// Each year is the MEAN of the daily MMCFD Petrobangla stated, over the days it
// filed ({span['first']} to {span['last']}); `days` is that count and `partial`
// marks a year the archive does not cover end to end. Years before the archive
// begins are absent rather than estimated.

export interface MacroGasYear {{
  year: string;
  /** Mean MMCFD from fields other than RPGCL's R-LNG terminal. */
  domestic: number;
  /** Mean MMCFD re-gasified at the R-LNG terminal. */
  lng: number;
  /** Days Petrobangla filed and the parser read, out of the year. */
  days: number;
  /** True when the archive does not cover the whole year. */
  partial: boolean;
}}

/** Domestic vs imported LNG supply transition (MMCFD), from the archive. */
export const macroGasData: readonly MacroGasYear[] = [
{body}
] as const;
"""


def main() -> int:
    if not TIMELINE.exists():
        print(json.dumps({"ok": False, "error": f"missing {TIMELINE}"}))
        return 1
    rows, span = build()
    if not rows:
        # A parser that found nothing is not a year with no gas.
        print(json.dumps({"ok": False, "error": "timeline holds no usable day"}))
        return 1
    text = render(rows, span)
    changed = not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text
    if changed:
        TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(json.dumps({
        "ok": True,
        "changed": changed,
        "years": len(rows),
        "first": rows[0]["year"],
        "last": rows[-1]["year"],
        "days": sum(r["days"] for r in rows),
        "skipped": sum(span["skipped"].values()),
    }))
    return 0


if __name__ == "__main__":
    sys.exit(main())
