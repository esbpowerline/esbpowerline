"""Rebuild the compiled day indexes from what is actually in public/data.

Two files, both imported as JS rather than read from disk, and both for the
same reason: a function bundle cannot see `public/data`.

`lib/available-dates.json` — every energy day the grid archive holds. The two
drift apart silently. 2026-08-01 was published as a data file but never added to
the index, so getLatestAvailableDate() returned 2026-07-31 and
isDateAvailable('2026-08-01') was false — the newest day the site had was
invisible to every code path that asks the index rather than the filesystem.

`lib/data/grid/recent-artifacts.json` — which of the four per-day artefacts the
last RECENT_DAYS days shipped with. The admin coverage screen needs this and
cannot get it any other way: `next.config.ts` excludes `public/data` from
`/admin/**` (it broke the 250 MB function limit) and excludes `plants/**` and
`curves/**` from *every* function, so on the deployed panel a directory listing
returns nothing and a day that shipped complete in the last deploy read as a day
that was never ingested. Kept to a short window on purpose — the screen shows 45
days, and indexing all 2,300 would put 80 KB in a bundle to answer a question
about six weeks.

Usage:
  python scripts/sync_available_dates.py [--apply]
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DAILY = REPO / "public" / "data" / "daily"
INDEX = REPO / "lib" / "available-dates.json"
PUBLIC = REPO / "public" / "data"
ARTIFACT_INDEX = REPO / "lib" / "data" / "grid" / "recent-artifacts.json"

# Comfortably more than the coverage strip's 45 days, so a deploy that lands a
# few days late still describes every square the panel draws.
RECENT_DAYS = 120

GAS_DAY_START = re.compile(rb'"gas_day_start"\s*:\s*"(\d{4}-\d{2}-\d{2})"')
REPORT_DAY_START = re.compile(rb'"report_date_start"\s*:\s*"(\d{4}-\d{2}-\d{2})"')


def gas_energy_days(cutoff: str) -> list[str]:
    """The energy day each recent Petrobangla file actually covers.

    The filename cannot be trusted: 2,238 of the archive's files are named for
    the morning the report was FILED, one day after the 08:00-08:00 window they
    describe. `gas_day_start` is the window's own start and is the only
    trustworthy key — `report_date_start` beside it is the header Petrobangla
    prints, which is wrong on 89 documents. Same rule as
    `ingest-coverage.server.ts`, which reads these files directly when it can.
    """
    directory = PUBLIC / "petrobangla" / "daily"
    if not directory.is_dir():
        return []
    days: set[str] = set()
    # A file named for D covers D or D-1, so look a little past the cutoff.
    for path in sorted(directory.glob("*.json")):
        if path.stem < cutoff:
            continue
        head = path.read_bytes()[:8192]
        m = GAS_DAY_START.search(head) or REPORT_DAY_START.search(head)
        if m:
            days.add(m.group(1).decode())
    return sorted(d for d in days if d >= cutoff)


def recent_artifacts() -> dict[str, object]:
    today = dt.date.today()
    cutoff = (today - dt.timedelta(days=RECENT_DAYS)).isoformat()
    lookback = (today - dt.timedelta(days=RECENT_DAYS + 2)).isoformat()

    def days_in(sub: str) -> list[str]:
        directory = PUBLIC / sub
        if not directory.is_dir():
            return []
        return sorted(p.stem for p in directory.glob("*.json") if p.stem >= cutoff)

    return {
        "_comment": (
            "Auto-generated by scripts/sync_available_dates.py. Which per-day artefacts the "
            f"last {RECENT_DAYS} days shipped with, for the admin coverage screen — a function "
            "bundle cannot list public/data. Do not hand-edit."
        ),
        "generatedFor": today.isoformat(),
        "grid": days_in("daily"),
        "curve": days_in("curves"),
        "plants": days_in("plants"),
        "gas": gas_energy_days(lookback),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    on_disk = sorted(p.stem for p in DAILY.glob("*.json") if not p.stem.startswith("_"))
    current = json.loads(INDEX.read_text(encoding="utf-8"))

    missing = sorted(set(on_disk) - set(current))
    stale = sorted(set(current) - set(on_disk))
    print(f"{len(on_disk)} day file(s) on disk, {len(current)} in the index")
    if missing:
        print(f"  {len(missing)} published but unindexed: {missing[:10]}")
    if stale:
        print(f"  {len(stale)} indexed but absent from disk: {stale[:10]}")
    # The artefact index is rewritten whenever it would change, independently of
    # the date index: a day can gain its curve or its gas long after the day
    # file itself landed, and that is exactly the change the coverage screen
    # exists to show.
    artifacts = recent_artifacts()
    artifacts_now = (
        json.loads(ARTIFACT_INDEX.read_text(encoding="utf-8")) if ARTIFACT_INDEX.exists() else None
    )
    artifacts_changed = artifacts_now != artifacts
    if artifacts_changed:
        counts = " ".join(f"{k}={len(v)}" for k, v in artifacts.items() if isinstance(v, list))
        print(f"  recent artefacts ({RECENT_DAYS}d): {counts}")

    if not missing and not stale and current == on_disk and not artifacts_changed:
        print("Index already matches.")
        return

    if not args.apply:
        print("Dry run — re-run with --apply.")
        return

    if missing or stale or current != on_disk:
        raw = INDEX.read_bytes()
        body = json.dumps(on_disk, indent=2)
        if b"\r\n" in raw:
            body = body.replace("\n", "\r\n")
        INDEX.write_bytes(body.encode("utf-8"))
        print(f"Rewrote {INDEX.relative_to(REPO)} with {len(on_disk)} dates.")

    if artifacts_changed:
        # LF and a trailing newline, so the Pi and this box write it the same
        # way — the lesson of the CRLF forecast rewrite (.gitattributes).
        ARTIFACT_INDEX.write_text(json.dumps(artifacts, indent=2) + "\n", encoding="utf-8", newline="\n")
        print(f"Rewrote {ARTIFACT_INDEX.relative_to(REPO)}.")


if __name__ == "__main__":
    main()
