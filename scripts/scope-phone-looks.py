"""Prefix every selector of a phone 'look' sheet with .gp[data-look='x'] so three
trial looks can ship in one bundle and be switched on the device (2026-11-12)."""
import io, re, sys

def scope_sel(sel, look):
    sel = sel.strip()
    tag = f".gp[data-look='{look}']"
    if re.search(r"\.gp(?![-\w])", sel):
        return re.sub(r"\.gp(?![-\w])", tag, sel, count=1)
    return f"{tag} {sel}"

def scope(css, look):
    out, i, n, depth_kf = [], 0, len(css), 0
    buf = ''
    stack = []
    while i < n:
        c = css[i]
        if css.startswith('/*', i):
            j = css.index('*/', i) + 2; out.append(css[i:j]); i = j; continue
        if c == '{':
            head = buf.strip(); buf = ''
            if head.startswith('@keyframes'):
                stack.append('kf'); out.append(head + ' {')
            elif head.startswith('@'):
                stack.append('at'); out.append(head + ' {')
            elif 'kf' in stack:
                stack.append('rule'); out.append(head + ' {')
            else:
                stack.append('rule'); out.append(', '.join(scope_sel(s, look) for s in head.split(',')) + ' {')
            i += 1; continue
        if c == '}':
            out.append(buf + '}'); buf = ''; stack.pop(); i += 1; continue
        if stack and stack[-1] == 'rule':
            j = css.index('}', i); out.append(css[i:j]); i = j; continue
        buf += c; i += 1
        if buf.strip() == '' and c == '\n': out.append('\n'); buf = ''
    return ''.join(out)

for look in sys.argv[1:]:
    src = io.open(f'app/grid-phone-look-{look}.css', encoding='utf-8').read()
    io.open(f'app/grid-phone-look-{look}.scoped.css', 'w', encoding='utf-8', newline='\n').write(
        f"/* GENERATED by scripts/scope-phone-looks.py from grid-phone-look-{look}.css - edit that file. */\n" + scope(src, look))
    print(look, 'ok')
