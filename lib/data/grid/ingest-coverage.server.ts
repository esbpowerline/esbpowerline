/**
 * What the site holds, and what it is still missing.
 *
 * The ingest screen used to answer one question — "what is the next day?" — by
 * adding a day to the latest file on disk. That is the right answer only when
 * the archive has no holes, and it has 81 of them. An operator could not see
 * which days were absent, which were present but incomplete, or how far behind
 * the site had fallen, so the only way to find a gap was to notice a chart
 * looking wrong months later.
 *
 * Four artifacts make a complete day, and they arrive from different places on
 * different schedules. Each one is a Grid Explorer tab:
 *
 *   * `daily/{E}.json`             the grid day — KPIs, fuel mix, outages
 *   * `petrobangla/daily/…`        the gas day — Gas & LNG Supply
 *   * `curves/{E}.json`            the half-hourly fuel curve — Energy Curve
 *   * `plants/{E}.json`            per-station detail — Power Stations
 *
 * A day with the first and not the second publishes with its gas columns blank,
 * which is exactly the sort of quiet incompleteness this screen names. The
 * curve and the station detail were left out of this count until 2026-09-11 —
 * they are exactly the two the publish route had once forgotten to release, and
 * a screen that does not look at them cannot report the failure it was built
 * for. The monthly report is counted too, but per month, not per day.
 *
 * **Where the answer comes from.** Release rows first, the filesystem second —
 * see `ingest-provenance.server.ts`. On the deployed panel the filesystem
 * answers nothing (the archive is excluded from the admin bundle) and the
 * curve and plants directories are excluded from every function, so disk alone
 * could never see a complete day. The database is also how the Pi's work
 * reaches this screen: it publishes the same release rows the panel does.
 */

const ISO_FILE = /^(\d{4}-\d{2}-\d{2})\.json$/;
const MONTH_FILE = /^(\d{4}-(?:0[1-9]|1[0-2]))\.json$/;
const ISO = /^\d{4}-\d{2}-\d{2}$/;
const MS_DAY = 86_400_000;

const shift = (iso: string, days: number): string =>
  new Date(Date.parse(`${iso}T00:00:00Z`) + days * MS_DAY).toISOString().slice(0, 10);

const daysBetween = (a: string, b: string): number =>
  Math.round((Date.parse(`${b}T00:00:00Z`) - Date.parse(`${a}T00:00:00Z`)) / MS_DAY);

/** DD-MM-YYYY, the shape PGCB uses in its filenames. */
const ddmmyyyy = (iso: string): string => {
  const [y, m, d] = iso.split('-');
  return `${d}-${m}-${y}`;
};

async function listDir(dir: string, re: RegExp): Promise<string[]> {
  try {
    const names = await readdir(path.join(process.cwd(), 'public', 'data', ...dir.split('/')));
    return names
      .map((n) => re.exec(n)?.[1])
      .filter((d): d is string => Boolean(d))
      .sort();
  } catch {
    return [];
  }
}

/**
 * Which energy day each Petrobangla file actually covers.
 *
 * The filename cannot be trusted: 2,238 of the archive's files are named for
 * the day the report was FILED, which is the morning after the 08:00–08:00
 * window they describe, while the other 59 are named for the window's own
 * start. So each file is asked, by reading the first few kilobytes and lifting
 * `gas_day_start` out of them — it sits about 2 KB in, well inside one read,
 * and a full pass over 2,297 files costs a few seconds.
 *
 * `gas_day_start`, specifically, and not the `report_date_start` sitting beside
 * it: that one is the header Petrobangla prints on the PDF, and it is wrong on
 * 89 documents. Reading it instead loses 84 real days and invents four. See
 * `petrobangla-day.server.ts` for the full count.
 *
 * Memoised against the directory's shape so that cost is paid once and again
 * only when a file is added.
 */
let gasIndexCache: { signature: string; days: Set<string> } | null = null;

async function gasEnergyDays(): Promise<Set<string>> {
  const files = await listDir('petrobangla/daily', ISO_FILE);
  const signature = `${files.length}:${files[files.length - 1] ?? ''}`;
  if (gasIndexCache?.signature === signature) return gasIndexCache.days;

  const dir = path.join(process.cwd(), 'public', 'data', 'petrobangla', 'daily');
  const days = new Set<string>();

  await Promise.all(
    files.map(async (name) => {
      let handle;
      try {
        handle = await open(path.join(dir, `${name}.json`), 'r');
        const buf = Buffer.alloc(8192);
        const { bytesRead } = await handle.read(buf, 0, 8192, 0);
        const head = buf.subarray(0, bytesRead).toString('utf8');
        // Alternation would match whichever key came first in the byte stream,
        // and `report_date_start` is always the earlier one — so ask for the
        // window explicitly, and only fall back if it is genuinely absent.
        const m =
          /"gas_day_start"\s*:\s*"(\d{4}-\d{2}-\d{2})"/.exec(head) ??
          /"report_date_start"\s*:\s*"(\d{4}-\d{2}-\d{2})"/.exec(head);
        // A file that will not say which window it covers is not counted: a
        // guess here would report coverage the site does not have.
        if (m) days.add(m[1]);
      } catch {
        // Unreadable file: not coverage.
      } finally {
        await handle?.close();
      }
    }),
  );

  gasIndexCache = { signature, days };
  return days;
}

export type DatasetCoverage = {
  id: 'grid' | 'gas' | 'curve' | 'plants' | 'monthly';
  label: string;
  /** One line: what it is and what it feeds. */
  what: string;
  unit: 'days' | 'months';
  held: number;
  first: string | null;
  last: string | null;
  /**
   * Slots inside the held span that the site lacks and a source is, or may
   * yet be, obtainable for. Holes the publisher never issued are not here.
   */
  missingInside: number;
  /** Holes inside the span the publisher never issued, counted apart. */
  neverPublished: number;
  /** The newest absences inside the span, newest first. */
  recentGaps: string[];
  /**
   * True when this row could only be counted over the recent window — the
   * deployed panel cannot list `public/data`, and only the grid days have a
   * compiled index of the whole archive.
   */
  windowOnly?: boolean;
};

/** One artefact of one day: held or not, and if held, by whom. */
export type ArtifactState = {
  held: boolean;
  /** Present only for an artefact held as a release row. */
  release?: ReleaseFact;
  /** True when a file on disk is the only evidence (a shipped deploy). */
  fromArchive?: boolean;
};

export type DayRow = {
  date: string;
  artifacts: Record<DayFeedId, ArtifactState>;
  /** How many of the four are held. Four is complete; zero is untouched. */
  heldCount: number;
  /** Hours of NLDC capture stored against this calendar day, 0–24. */
  hours: number;
};

export type IngestCoverage = {
  /** The civil day in Dhaka — what "behind" is measured against. */
  today: string;
  /** The newest energy day whose sources PGCB will have posted by now. */
  newestPublishable: string;
  datasets: DatasetCoverage[];
  /** Heartbeat of the automations, so "is the Pi alive" is on this screen. */
  pulse: AutomationPulse;
  /** True when the release layer could not be read and this is disk only. */
  degraded: boolean;
  /** The last stretch of energy days, newest first, with what we hold for each. */
  recent: DayRow[];
  /** Days the site does not have at all, newest first, with their filenames. */
  awaiting: Array<{ date: string; workbook: string; gasFiledUnder: string }>;
  /** Days held with no gas: they publish with the gas columns blank. */
  gasMissing: string[];
  /** Days held with no station detail. */
  plantsMissing: string[];
  /** Days held with no fuel curve: the Energy Curve tab is empty for them. */
  curveMissing: string[];
  /** Months inside the monthly span the site lacks and PGCB did publish. */
  monthsMissing: string[];
  /** Months inside the span PGCB never published, with why. */
  monthsNeverPublished: Array<{ month: string; why: string }>;
  /** How many days behind `newestPublishable` the newest held day is. */
  daysBehind: number | null;
};

function gapsInside(held: string[], step: (iso: string, n: number) => string): string[] {
  if (held.length < 2) return [];
  const set = new Set(held);
  const out: string[] = [];
  for (let d = step(held[0], 1); d < held[held.length - 1]; d = step(d, 1)) {
    if (!set.has(d)) out.push(d);
  }
  return out;
}

const monthStep = (key: string, n: number): string => {
  const idx = Number(key.slice(0, 4)) * 12 + Number(key.slice(5, 7)) - 1 + n;
  return `${Math.floor(idx / 12)}-${String((idx % 12) + 1).padStart(2, '0')}`;
};

/** How many days back the per-day strip reaches. */
const RECENT_WINDOW = 45;

/**
 * Distinct NLDC hours stored per energy day, for the window the strip draws.
 *
 * The hourly capture is the one stream nobody can re-fetch after ~145 days, so
 * "22 of 24 hours" on a day is worth seeing beside that day's four artefacts.
 * Grouped in Postgres rather than pulled row by row: 45 days is ~4,300
 * observations across the four series and the panel only needs the count.
 *
 * Dhaka, not UTC. `observedAt` is an instant; bucketing it by UTC date would
 * file every hour from 00:00 to 06:00 Dhaka under the previous day and show a
 * permanent six-hour hole on today's square.
 *
 * Distinct HOURS, not distinct instants. NLDC occasionally posts a half-hour
 * reading — 2026-09-10 carries a 13:30 row beside its 13:00 — so counting
 * instants reported 25 of 24 hours for four of the last six days. The question
 * the square answers is which of the day's 24 hours we hold, and 13:00 and
 * 13:30 are the same hour.
 */
async function hoursByDay(fromKey: string): Promise<Map<string, number>> {
  const out = new Map<string, number>();
  try {
    const prisma = (await import('@/lib/prisma')).default;
    const rows = await prisma.$queryRaw<Array<{ day: string; hours: bigint }>>`
      select to_char("observedAt" at time zone 'Asia/Dhaka', 'YYYY-MM-DD') as day,
             count(distinct date_trunc('hour', "observedAt" at time zone 'Asia/Dhaka')) as hours
        from "GridHourlyObservation"
       where "observedAt" >= (${fromKey}::date at time zone 'Asia/Dhaka')
       group by 1
    `;
    for (const row of rows) out.set(row.day, Number(row.hours));
  } catch {
    // No database, or the table is absent on this checkout. The strip then
    // reports no hours rather than failing the screen.
  }
  return out;
}

export const getIngestCoverage = cache(async (): Promise<IngestCoverage> => {
  const today = downloadStamp().iso;
  // PGCB posts the workbook for energy day E on the morning of E+1, and
  // Petrobangla files E's gas window under E+1 as well. So the newest day whose
  // sources exist anywhere is yesterday.
  const newestPublishable = shift(today, -1);
  const windowStart = shift(newestPublishable, -(RECENT_WINDOW - 1));

  const [
    gridFiles,
    curveFiles,
    plantFiles,
    monthFiles,
    gasDays,
    publishedGrid,
    publishedGas,
    publishedCurve,
    publishedPlants,
    publishedMonths,
    facts,
    pulse,
    hourCounts,
  ] = await Promise.all([
    listDir('daily', ISO_FILE),
    listDir('curves', ISO_FILE),
    listDir('plants', ISO_FILE),
    listDir('pgcb-monthly', MONTH_FILE),
    gasEnergyDays(),
    getPublishedKeys('GRID_DAILY'),
    getPublishedKeys('GAS_DAILY'),
    getPublishedKeys('GRID_CURVE'),
    getPublishedKeys('GRID_PLANTS'),
    getPublishedKeys('PGCB_MONTHLY'),
    // Publish times and actors, for the window the strip draws only.
    getRecentReleaseFacts([...DAY_FEED_IDS] as DataFeed[], windowStart),
    getAutomationPulse(),
    hoursByDay(windowStart),
  ]);

  // A day published at runtime counts as held even though no file exists: that
  // is the whole point of the release layer, and a screen that ignored it would
  // send an operator to re-ingest a day already on the site.
  //
  // Three layers, and each is needed. The filesystem answers on a developer's
  // machine and for the whole archive. The compiled index answers on the
  // deployed panel for the recent window, which is all this screen draws. The
  // release rows answer for anything published since the last deploy — and
  // they are also how the Pi's work reaches this screen at all.
  const iso = (keys: string[]) => keys.filter((k) => ISO.test(k));
  // `availableDates` is the full compiled list of grid days, so the grid row's
  // span is right everywhere. The other three have no such index — building one
  // for 2,300 days to answer a question about six weeks is not worth the bundle
  // — so where the filesystem is unavailable their totals describe the recent
  // window only, and the table says so rather than quietly under-reporting.
  const hasArchiveOnDisk = gridFiles.length > 0;
  const grid = [
    ...new Set([...gridFiles, ...availableDates, ...recentArtifacts.grid, ...iso(publishedGrid)]),
  ].sort();
  const curve = [...new Set([...curveFiles, ...recentArtifacts.curve, ...iso(publishedCurve)])].sort();
  const plants = [
    ...new Set([...plantFiles, ...recentArtifacts.plants, ...iso(publishedPlants)]),
  ].sort();
  for (const key of recentArtifacts.gas) gasDays.add(key);
  for (const key of publishedGas) if (ISO.test(key)) gasDays.add(key);
  const gas = [...gasDays].sort();
  const months = [
    ...new Set([
      ...monthFiles,
      ...monthlyRecords.map((m) => m.date_key),
      ...publishedMonths.filter((k) => /^\d{4}-\d{2}$/.test(k)),
    ]),
  ].sort();

  const heldSets: Record<DayFeedId, Set<string>> = {
    GRID_DAILY: new Set(grid),
    GAS_DAILY: new Set(gas),
    GRID_CURVE: new Set(curve),
    GRID_PLANTS: new Set(plants),
  };

  const recent: DayRow[] = [];
  for (let i = 0; i < RECENT_WINDOW; i += 1) {
    const date = shift(newestPublishable, -i);
    const artifacts = {} as Record<DayFeedId, ArtifactState>;
    let heldCount = 0;
    for (const feed of DAY_FEED_IDS) {
      const release = facts.byFeed[feed]?.[date];
      const held = heldSets[feed].has(date);
      if (held) heldCount += 1;
      artifacts[feed] = release
        ? { held: true, release }
        : { held, ...(held ? { fromArchive: true } : {}) };
    }
    recent.push({ date, artifacts, heldCount, hours: hourCounts.get(date) ?? 0 });
  }

  const latestGrid = grid[grid.length - 1] ?? null;
  const awaiting = recent
    .filter((r) => !r.artifacts.GRID_DAILY.held)
    .map((r) => ({
      date: r.date,
      // The workbook is named for the publication date, a day after the energy
      // day it describes.
      workbook: `Daily Report ${ddmmyyyy(shift(r.date, 1))}.xlsx`,
      gasFiledUnder: shift(r.date, 1),
    }));

  // A hole is either ours or the publisher's. Only grid days and monthly
  // reports have evidence for the second kind (see publisher-gaps.ts); for the
  // gas, curve and station rows every hole is counted as the site's.
  const gridGaps = splitGaps(gapsInside(grid, shift), (d) => PGCB_DAYS_WITHOUT_SOURCE.has(d));
  const monthGaps = splitGaps(gapsInside(months, monthStep), (m) => m in PGCB_MONTHS_NEVER_PUBLISHED);
  const ours = (keys: string[]) => ({ missing: gapsInside(keys, shift), neverPublished: [] as string[] });
  const gasGaps = ours(gas);
  const curveGaps = ours(curve);
  const plantGaps = ours(plants);

  const datasets: DatasetCoverage[] = [
    {
      id: 'grid',
      label: 'Grid day',
      what: 'PGCB’s daily workbook — peaks, generation by fuel, the load curve, outages.',
      unit: 'days',
      held: grid.length,
      first: grid[0] ?? null,
      last: latestGrid,
      missingInside: gridGaps.missing.length,
      recentGaps: gridGaps.missing.slice(-8).reverse(),
      neverPublished: gridGaps.neverPublished.length,
    },
    {
      id: 'gas',
      label: 'Gas day',
      what: 'Petrobangla’s 08:00–08:00 intake–offtake report — field production and offtake.',
      unit: 'days',
      held: gas.length,
      first: gas[0] ?? null,
      last: gas[gas.length - 1] ?? null,
      missingInside: gasGaps.missing.length,
      recentGaps: gasGaps.missing.slice(-8).reverse(),
      neverPublished: gasGaps.neverPublished.length,
      windowOnly: !hasArchiveOnDisk,
    },
    {
      id: 'curve',
      label: 'Energy curve',
      what: 'The half-hourly generation-by-fuel curve behind the Energy Curve tab.',
      unit: 'days',
      held: curve.length,
      first: curve[0] ?? null,
      last: curve[curve.length - 1] ?? null,
      missingInside: curveGaps.missing.length,
      recentGaps: curveGaps.missing.slice(-8).reverse(),
      neverPublished: curveGaps.neverPublished.length,
      windowOnly: !hasArchiveOnDisk,
    },
    {
      id: 'plants',
      label: 'Station detail',
      what: 'Per-station evening peak — the Power Stations tab.',
      unit: 'days',
      held: plants.length,
      first: plants[0] ?? null,
      last: plants[plants.length - 1] ?? null,
      missingInside: plantGaps.missing.length,
      recentGaps: plantGaps.missing.slice(-8).reverse(),
      neverPublished: plantGaps.neverPublished.length,
      windowOnly: !hasArchiveOnDisk,
    },
    {
      id: 'monthly',
      label: 'Monthly report',
      what: 'PGCB’s monthly document — Macro Trends’ PGCB Monthly Archives.',
      unit: 'months',
      held: months.length,
      first: months[0] ?? null,
      last: months[months.length - 1] ?? null,
      missingInside: monthGaps.missing.length,
      recentGaps: monthGaps.missing.slice(-8).reverse(),
      neverPublished: monthGaps.neverPublished.length,
      // Whole archive everywhere now: the month list is compiled in above.
    },
  ];

  // "Missing" is only meaningful for a day whose grid half exists: until PGCB
  // files the workbook there is nothing for the other three to belong to.
  const missingWhereGridHeld = (feed: DayFeedId) =>
    recent.filter((r) => r.artifacts.GRID_DAILY.held && !r.artifacts[feed].held).map((r) => r.date);

  return {
    today,
    newestPublishable,
    datasets,
    pulse,
    degraded: facts.degraded,
    recent,
    awaiting,
    gasMissing: missingWhereGridHeld('GAS_DAILY'),
    plantsMissing: missingWhereGridHeld('GRID_PLANTS'),
    curveMissing: missingWhereGridHeld('GRID_CURVE'),
    monthsMissing: monthGaps.missing.slice(-6).reverse(),
    monthsNeverPublished: monthGaps.neverPublished.map((month) => ({
      month,
      why: PGCB_MONTHS_NEVER_PUBLISHED[month],
    })),
    daysBehind: latestGrid ? daysBetween(latestGrid, newestPublishable) : null,
  };
});
